def seed_test(*, wipe: bool = True) -> dict:
    config.ensure_dirs()
    db.init_db(config.TEST_DB_PATH)
    with db.session("test") as conn:
        if wipe:
            # test DB file is dedicated; wipe all rows
            conn.execute("DELETE FROM classifications")
            conn.execute("DELETE FROM responses")
        ids = []
        for i, row in enumerate(TEST_RESPONSES):
            # Stamp created_at diversity via sequential inserts (same second ok)
            ch = hashlib.sha256(
                f"test-{i}|{row['q1']}|{row['q2']}|{row['q3']}|{row['q4']}".encode()
            ).hexdigest()
            feats = classify.classify_response(row["q1"], row["q2"], row["q3"], row["q4"])
            rid = db.insert_response(
                conn,
                q1=row["q1"],
                q2=row["q2"],
                q3=row["q3"],
                q4=row["q4"],
                dataset="test",
                content_hash=ch,
                client_submit_token=f"test-seed-{i}",
                classifications=feats,
            )
            ids.append(rid)
        return {"ok": True, "count": len(ids), "response_ids": ids, "db": str(config.TEST_DB_PATH)}


if __name__ == "__main__":
    print(seed_test())
